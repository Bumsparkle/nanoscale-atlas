function merge<T>(base: T, over: Overrides<T>): T {
  const out = structuredClone(base) as Record<string, unknown>
  for (const [k, v] of Object.entries(over as Record<string, unknown>)) {
    if (!(k in out)) throw new Error('light palette: unknown token ' + k)
    out[k] = v && typeof v === 'object' ? merge(out[k], v as never) : v
  }
  return out as T
}

export const PALETTES: Record<Theme, ScenePalette> = { dark: DARK, light: merge(DARK, LIGHT) }

/** the live palette for the current theme */
export const P: ScenePalette = structuredClone(PALETTES[useTheme.getState().theme])

const assign = (to: Record<string, unknown>, from: Record<string, unknown>) => {
  for (const [k, v] of Object.entries(from)) {
    if (v && typeof v === 'object') assign(to[k] as Record<string, unknown>, v as Record<string, unknown>)
    else to[k] = v
  }
}
const listeners = new Set<(t: Theme) => void>()
/** run before React re-renders: caches drop their old materials here */
export function onSceneTheme(fn: (t: Theme) => void) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}
useTheme.subscribe((s, prev) => {
  if (s.theme === prev.theme) return
  assign(P as never, PALETTES[s.theme] as never)
  for (const fn of listeners) fn(s.theme)
})

/** the resolved theme, for keys and effect dependencies in scene components */
export const useSceneTheme = () => useTheme((s) => s.theme)
